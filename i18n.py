_MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
           "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def lang() -> str:
    """'fr' when Anki's interface language is French, else 'en'."""
    try:
        from anki import lang as anki_lang
        code = anki_lang.current_lang or ""
    except Exception:
        code = ""
    return "fr" if str(code).lower().startswith("fr") else "en"


def t(key: str, **kw) -> str:
    text = STRINGS[lang()][key]
    return text.format(**kw) if kw else text


def label(key: str) -> str:
    """A field label with the language's colon spacing ('Durée :' / 'Duration:')."""
    return t("label_colon", label=t(key))


def strings(*keys: str) -> dict:
    """A subset of the current strings, for handing to page JavaScript."""
    table = STRINGS[lang()]
    return {k: table[k] for k in keys}


def fmt_num(value: float, places: int = 2) -> str:
    """16.17 → '16,17' in French; whole numbers drop their decimals."""
    value = round(float(value), places)
    if abs(value) < 10 ** (-places):
        value = 0.0
    text = str(int(value)) if value.is_integer() else f"{value:.{places}f}".rstrip("0").rstrip(".")
    return text.replace(".", ",") if lang() == "fr" else text


def fmt_pct(value: float) -> str:
    return f"{fmt_num(value)} %" if lang() == "fr" else f"{fmt_num(value)}%"


def fmt_date(d: date) -> str:
    if lang() == "fr":
        return d.strftime("%d/%m/%Y")
    return f"{d.day} {_MONTHS[d.month - 1]} {d.year}"
